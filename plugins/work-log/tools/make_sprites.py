"""Cuts the 8 Kanto gym badge icons out of the FireRed/LeafGreen Trainer Card sheet and writes them as vector pixel art
(hooks/sprites.ts), so the panel draws them crisp at any size with no image file to load.

The sheet is Nintendo / Game Freak art ripped by the community (Spriters Resource, asset 3856). Private use only:
keep assets/ and hooks/sprites.ts out of any public repository.

usage: python make_sprites.py
"""
import pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHEET = ROOT / 'assets' / 'frlg' / 'fr_3856_trainercardkit.png'
OUT = ROOT / 'hooks' / 'sprites.ts'
X0, Y0, N, S, PITCH = 8, 858, 8, 16, 18   # first icon corner, count, icon size, distance between icons
NAMES = ['Boulder', 'Cascade', 'Thunder', 'Rainbow', 'Soul', 'Marsh', 'Volcano', 'Earth']

sheet = Image.open(SHEET).convert('RGBA')
key = sheet.getpixel((X0, Y0))[:3]   # the orange the sheet uses as "no pixel"


def tile(i):
    return sheet.crop((X0 + PITCH * i, Y0, X0 + PITCH * i + S, Y0 + S))


def hex_of(c):
    return '#%02x%02x%02x' % c[:3]


def runs(img, recolor=None):
    """One path per colour: horizontal runs of 1px-tall rects. Returns the SVG markup."""
    by = {}
    for y in range(img.height):
        x = 0
        while x < img.width:
            p = img.getpixel((x, y))
            if p[3] == 0 or p[:3] == key:
                x += 1
                continue
            e = x + 1
            while e < img.width and img.getpixel((e, y)) == p:
                e += 1
            col = recolor or hex_of(p)
            by[col] = by.get(col, '') + f'M{x} {y}h{e - x}v1h-{e - x}z'
            x = e
    return ''.join(f'<path fill="{c}" d="{d}"/>' for c, d in by.items())


# the sheet's badges are grey (trainer card style): tint each by its game colour, keeping the shading
BASE = [(0x9a, 0x9a, 0xa4), (0x3f, 0x9a, 0xf0), (0xf8, 0xd0, 0x28), None, (0xf0, 0x6c, 0xa8), (0xa8, 0x62, 0xd8), (0xe8, 0x4c, 0x2c), (0x4c, 0xb0, 0x48)]
RAINBOW = [(0xe8, 0x40, 0x40), (0xf0, 0x90, 0x30), (0xf0, 0xd8, 0x30), (0x50, 0xc0, 0x50), (0x40, 0xa0, 0xf0), (0x90, 0x60, 0xe0)]


def tint(img, i):
    out = img.copy()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = img.getpixel((x, y))
            if a == 0 or (r, g, b) == key:
                continue
            base = BASE[i] or RAINBOW[min(5, x * 6 // img.width)]
            v = min(1, max(0, (r / 255 - .12) / .7))
            if v < .75:
                k = v / .75
                col = [c * (.15 + .85 * k) for c in base]
            else:
                k = (v - .75) / .25
                col = [c + (255 - c) * .38 * k for c in base]
            out.putpixel((x, y), (*[round(c) for c in col], a))
    return out


art = [runs(tint(tile(i), i)) for i in range(N)]
sil = [runs(tile(i), '#2b3a5c') for i in range(N)]   # an empty slot: the same shape in dark slate

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_sprites.py from the FireRed/LeafGreen Trainer Card sheet. Do not edit by hand, do not publish.\n')
    f.write(f'export const BADGE_NAMES = {NAMES!r}\n'.replace("'", '"'))
    f.write('// 16 by 16 pixel art, one string of paths per badge\n')
    f.write('export const BADGE_ART: string[] = [\n' + ''.join(f'  `{a}`,\n' for a in art) + ']\n')
    f.write('export const BADGE_EMPTY: string[] = [\n' + ''.join(f'  `{a}`,\n' for a in sil) + ']\n')
print('wrote', OUT, 'key', key)
