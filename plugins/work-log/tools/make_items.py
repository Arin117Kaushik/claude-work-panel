"""Turns the 24 by 24 pixel item icons in assets/items into vector pixel art (hooks/items.ts).
Icons are Game Freak / Nintendo art (Pokemon Showdown's item icon set). Private use only: keep assets/ and hooks/items.ts out of any public repository.
usage: python make_items.py"""
import pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'hooks' / 'items.ts'


def redden(im):  # this icon set paints the Poke Ball orange; make it the proper red
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = im.getpixel((x, y))
            if a > 100 and r > 0xc0 and 0x40 < g < 0xa8 and b < 0x60:
                im.putpixel((x, y), (r, int(g * .28), int(b * .6), a))
    return im


def markup(im):
    by = {}
    for y in range(im.height):
        x = 0
        while x < im.width:
            p = im.getpixel((x, y))
            if p[3] < 128:
                x += 1
                continue
            e = x + 1
            while e < im.width and im.getpixel((e, y)) == p:
                e += 1
            by.setdefault(p[:3], []).append((x, e, y))
            x = e
    out = []
    for c, runs in by.items():
        d = ''.join(f'M{a} {y}h{b - a}v1h-{b - a}z' for a, b, y in runs)
        out.append(f'<path fill="#%02x%02x%02x" d="{d}"/>' % c)
    return ''.join(out)


with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_items.py from assets/items. Do not edit by hand, do not publish.\nexport const ITEMS: Record<string, string> = {\n')
    for p in sorted((ROOT / 'assets' / 'items').glob('*.png')):
        f.write(f"  '{p.stem}': `{markup(redden(Image.open(p).convert('RGBA')) if p.stem == 'poke-ball' else Image.open(p).convert('RGBA'))}`,\n")
    f.write('}\n')
print('wrote', OUT, OUT.stat().st_size)
