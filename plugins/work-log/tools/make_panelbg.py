"""Builds the /work panel's background (hooks/panelbg.ts) from the real FireRed/LeafGreen Pokemon Center map.
The room is 15 tiles wide; the panel is taller and wider, so the counter wall is kept (left and right ends as they are,
the middle column repeated to widen it) and the floor row is repeated downwards. A dark tint keeps the text readable.
Nintendo / Game Freak art, private use only: keep assets/ and hooks/panelbg.ts out of any public repository.
usage: python make_panelbg.py"""
import pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAP = ROOT / 'assets' / 'pokecenter_3724.png'
OUT = ROOT / 'hooks' / 'panelbg.ts'
X0, Y0, T = 8, 22, 16          # the 1F room starts here in the map
W, H = 20, 26                  # tiles in the panel background
TOP_ROWS, FLOOR_ROW = 4, 5     # rows kept as they are, then the row repeated down


def runs(img):
    by = {}
    for y in range(img.height):
        x = 0
        while x < img.width:
            p = img.getpixel((x, y))
            e = x + 1
            while e < img.width and img.getpixel((e, y)) == p:
                e += 1
            by.setdefault(p, []).append((x, e, y))
            x = e
    out = []
    for p, rs in by.items():
        d = ''.join(f'M{a} {y}h{b - a}v1h-{b - a}z' for a, b, y in rs)
        out.append(f'<path fill="#%02x%02x%02x" d="{d}"/>' % p)
    return ''.join(out)


def src_col(tx):
    if tx < 7: return tx
    if tx >= W - 7: return 8 + (tx - (W - 7))
    return 7


def src_row(ty):
    return ty if ty < TOP_ROWS else FLOOR_ROW


room = Image.open(MAP).convert('RGB')
ids, defs, rows = {}, '', ''
for ty in range(H):
    row = ''
    for tx in range(W):
        c = src_col(tx) if ty < TOP_ROWS else 3 + tx % 2   # below the counter wall: plain floor tiles only
        sx, sy = X0 + c * T, Y0 + src_row(ty) * T
        t = room.crop((sx, sy, sx + T, sy + T))
        k = t.tobytes()
        if k not in ids:
            ids[k] = 't%d' % len(ids)
            defs += f'<g id="{ids[k]}">{runs(t)}</g>'
        row += f'<use href="#{ids[k]}" x="{tx * T}"/>'
    rows += f'<g transform="translate(0 {ty * T})">{row}</g>'
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W * T} {H * T}" preserveAspectRatio="xMidYMin slice" shape-rendering="crispEdges">'
       f'<defs>{defs}</defs>{rows}<rect width="{W * T}" height="{H * T}" fill="#1a0c14" fill-opacity=".72"/></svg>')
assert len(svg) < 126000, len(svg)
OUT.write_text('// Generated by tools/make_panelbg.py. Do not edit by hand, do not publish.\nexport const PANEL_BG = `' + svg + '`\nexport const PANEL_BG_W = %d\nexport const PANEL_BG_H = %d\n' % (W * T, H * T), encoding='utf-8')
print(len(ids), 'tiles', len(svg), 'chars')
